import { expect, test } from '@playwright/test'

test('Recorrido del docente en un navegador limpio', async ({page,request}) => {
  const errores:string[] = []
  page.on('pageerror', error => errores.push(error.message))
  page.on('console', msg => { if (['warning','error'].includes(msg.type())) errores.push(msg.text()) })
  page.on('response', r => { if (r.status()>=400) errores.push(r.status()+' '+r.url()) })
  await page.goto('/')
  const conteo = page.locator('#conteo')
  await expect(conteo).toHaveText('10 recuerdos')
  await expect(page.locator('.tallo')).toHaveCount(6)
  expect((await request.get('/favicon.ico')).status()).toBe(200)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.getByRole('button',{name:'Plantar un recuerdo',exact:true}).click()
  const hoja=page.getByRole('dialog')
  await hoja.getByLabel('Título').fill('Flor de revisión')
  await hoja.getByLabel('Frase').fill('Una frase para el laboratorio.')
  await hoja.getByLabel('Fecha').fill('2026-11-18')
  await hoja.getByLabel('Emoción').selectOption('amor')
  await hoja.getByLabel('Categoría').fill('Prueba')
  await hoja.getByRole('button',{name:'Plantar recuerdo',exact:true}).click()
  await expect(conteo).toHaveText('11 recuerdos')
  await page.reload()
  const ficha=page.locator('.ficha').filter({hasText:'Flor de revisión'})
  await ficha.click()
  await expect(hoja).toContainText('Una frase para el laboratorio.')
  await hoja.getByRole('button',{name:'Editar recuerdo'}).click()
  await hoja.getByLabel('Título').fill('Flor revisada')
  await hoja.getByLabel('Frase').fill('Ya floreció.')
  await hoja.getByLabel('Fecha').fill('2026-06-01')
  await hoja.getByLabel('Emoción').selectOption('gratitud')
  await hoja.getByLabel('Categoría').fill('Universidad')
  await hoja.getByRole('button',{name:'Guardar cambios'}).click()
  await page.reload()
  const busqueda=page.getByRole('search')
  await busqueda.getByLabel('Emoción').selectOption('gratitud')
  await busqueda.getByLabel('Mes',{exact:true}).fill('2026-06')
  await busqueda.getByRole('searchbox').fill('florecio')
  await expect(conteo).toHaveText('1 de 11 recuerdos')
  await busqueda.getByRole('searchbox').fill('sin coincidencias')
  await expect(conteo).toHaveText('0 de 11 recuerdos')
  await page.getByRole('button',{name:'Limpiar filtros'}).click()
  await page.locator('.ficha').filter({hasText:'Flor revisada'}).click()
  await expect(hoja).toContainText('Gratitud · Universidad')
  await hoja.getByRole('button',{name:'Arrancar flor'}).click()
  await hoja.getByRole('button',{name:'Cancelar'}).click()
  await expect(hoja).toContainText('Ya floreció.')
  await hoja.getByRole('button',{name:'Arrancar flor'}).click()
  await hoja.getByRole('button',{name:'Arrancar esta flor',exact:true}).click()
  await expect(conteo).toHaveText('10 recuerdos')
  await page.reload()
  await expect(conteo).toHaveText('10 recuerdos')
  await expect(page.locator('.ficha').filter({hasText:'Flor revisada'})).toHaveCount(0)
  expect(errores).toEqual([])
})
test('El formulario conserva la frase cuando el navegador rechaza la escritura', async ({page})=>{
  await page.goto('/')
  await expect(page.locator('#conteo')).toHaveText('10 recuerdos')
  await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new DOMException('Sin espacio','QuotaExceededError')}})
  await page.getByRole('button',{name:'Plantar un recuerdo',exact:true}).click()
  const hoja=page.getByRole('dialog')
  await hoja.getByLabel('Título').fill('Un recuerdo por guardar')
  await hoja.getByLabel('Frase').fill('Esta frase debe conservarse.')
  await hoja.getByLabel('Emoción').selectOption('calma')
  await hoja.getByLabel('Categoría').fill('Prueba')
  await hoja.getByRole('button',{name:'Plantar recuerdo',exact:true}).click()
  await expect(hoja.getByRole('alert')).toContainText('No se pudo guardar')
  await expect(hoja.getByLabel('Frase')).toHaveValue('Esta frase debe conservarse.')
  await page.reload()
  await expect(page.locator('#conteo')).toHaveText('10 recuerdos')
})
